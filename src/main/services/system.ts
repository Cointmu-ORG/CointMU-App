import { app, ipcMain } from "electron";
import { readFileSync } from "node:fs";
import { cpus } from "node:os";
import { join } from "node:path";
import { SYSTEM_CHANNELS } from "../../bridge/ipc-channels";
import type { AppInfo } from "../../bridge/types";

const CPU_SAMPLE_DELAY_MS = 200;
export const FALLBACK_BUILD_ID = "00000000";
const MS_PER_SECOND = 1000;

interface CpuTicks {
  idle: number;
  total: number;
}

/**
 * Captures a point-in-time aggregate of CPU scheduler ticks summed across every
 * logical core. The total spans all time categories while idle isolates the
 * idle category, enabling a load ratio to be derived from two spaced samples.
 * @returns The aggregated idle and total tick counts.
 */
function sampleCpuTicks(): CpuTicks {
  let idle = 0;
  let total = 0;
  for (const cpu of cpus()) {
    for (const value of Object.values(cpu.times)) {
      total += value;
    }
    idle += cpu.times.idle;
  }
  return { idle, total };
}

/**
 * Suspends for the given duration without blocking the event loop.
 * @param ms - The delay in milliseconds.
 * @returns A promise that resolves once the delay elapses.
 */
function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function readJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, "utf-8")) as Record<string, unknown>;
}

/**
 * Reads the app version, codename and build id from the app root. Runs once at
 * startup; the sandboxed preload cannot read files itself.
 * @param appRoot - Folder holding package.json and build-info.json.
 * @returns The version metadata; the build id falls back when build-info.json
 * is missing (it is generated by the prebuild step).
 */
export function readAppInfo(appRoot: string): Omit<AppInfo, "startedAtMs"> {
  const pkg = readJson(join(appRoot, "package.json"));
  let build = FALLBACK_BUILD_ID;
  try {
    const buildInfo = readJson(join(appRoot, "build-info.json"));
    if (typeof buildInfo.build === "string") build = buildInfo.build;
  } catch {
    // No build-info.json (e.g. a dev checkout before the first build).
  }
  return {
    version: String(pkg.version),
    codename: typeof pkg.codename === "string" ? pkg.codename : "",
    build,
  };
}

/**
 * Registers system telemetry IPC handlers on the main process. The get-cpu-usage
 * handler measures live machine CPU load by computing the delta between idle and
 * total scheduler ticks across two samples spaced by a short interval, returning
 * the busy fraction in the range [0, 1] (for example 0.31 for 31 percent).
 * @returns Nothing.
 */
export function registerSystemHandlers(): void {
  const appInfo: AppInfo = {
    ...readAppInfo(app.getAppPath()),
    startedAtMs: Date.now() - process.uptime() * MS_PER_SECOND,
  };
  // Synchronous on purpose: the preload builds window.systemInfo before the
  // page runs, and the renderer reads it synchronously while rendering.
  ipcMain.on(SYSTEM_CHANNELS.GET_APP_INFO, (event) => {
    event.returnValue = appInfo;
  });

  ipcMain.handle("get-cpu-usage", async (): Promise<number> => {
    const start = sampleCpuTicks();
    await delay(CPU_SAMPLE_DELAY_MS);
    const end = sampleCpuTicks();

    const idleDelta = end.idle - start.idle;
    const totalDelta = end.total - start.total;

    if (totalDelta <= 0) {
      return 0;
    }

    const usage = 1 - idleDelta / totalDelta;
    return Math.min(1, Math.max(0, usage));
  });
}
